<p>A free permit is required to bicycle in historic Spring Grove Cemetery & Arboretum (4521 Spring Grove Ave., Cincinnati, OH 45232).</p>

<p>Online information is conflicting and <strikethrough>enshitified</strikethrough> amplified by AI, so here is an original source.</p>

<p>Register at <a href="https://www.springgrove.org/locations/spring-grove-cemetery-arboretum/" target="_blank">Customer Service Center</a> — located just inside the main gate entrance — to complete permit form.</p>

<p><b>RULES OF THE ROAD</b></p>
<ul>
	<li>Pass must be visible while riding.</li>
	<li>Stay at least 50 feet away from funeral processions and gravesite burials.</li>
	<li>No biking on Fridays - Saturdays between 10:00 AM - 3:00 PM.</li>
	<li>Avoid roads marked with white, yellow, and green lines.</li>
	<li>Max 4 bikers per group; larger groups must split.</li>
	<li>Up to 3 minors may ride with an adult passholder; supervision required.</li>
	<li>Ride in a straight line; avoid weaving.</li>
	<li>No excessive speed.</li>
	<li>Look left-right-left before entering roadways.</li>
	<li>Be aware of surroundings.</li>
	<li>Helmet use and avoiding electronics are strongly suggested.</li>
	<li>Do not carry items that affect control.</li>
	<li>Spring Grove is not liable for injuries, loss, theft, or damage.</li>
	<li>Annual permit renewal required.</li>
</ul>
